/* A swing found, its frequency and half amplitude in their ranges */
static void
check_swing (const char *name, const uint8_t *s, unsigned n, bool want, float lo_hz = 0, float hi_hz = 0,
             float lo_amp = 0, float hi_amp = 0)
{
	hl::DriveBoard::Swing swing = {};
	bool found = hl::DriveBoard::find_swing (s, n, swing);
	char what[96];

	snprintf (what, sizeof (what), "%s: a swing", name);
	CHECK (what, found, want);
	if (!found || !want)
		return;
	float hz = hl::DriveBoard::NMI_HZ / swing.period;
	snprintf (what, sizeof (what), "%s: %.1f Hz", name, hz);
	CHECK (what, hz >= lo_hz && hz <= hi_hz, 1);
	snprintf (what, sizeof (what), "%s: %.1f steps", name, swing.amplitude);
	CHECK (what, swing.amplitude >= lo_amp && swing.amplitude <= hi_amp, 1);
	snprintf (what, sizeof (what), "%s: the mean %.1f", name, swing.mean);
	CHECK (what, swing.mean > 0x78 && swing.mean < 0x88, 1);
}

static void
test_swings ()
{
	uint8_t s[128];
	unsigned i;

	check_swing ("road effect 01", effect_01, 128, true, 15, 30, 7, 12);
	check_swing ("road effect 04", effect_04, 128, true, 15, 35, 6, 11);
	check_swing ("road effect 05", effect_05, 128, true, 10, 15, 4, 8);
	check_swing ("road effect 06, slow", effect_06, 128, false);
	check_swing ("road effect 02, a bump", effect_02, 128, false);
	for (i = 0; i < 128; i++)
		s[i] = (uint8_t) lrintf (128 + 8 * sinf (2 * 3.14159265f * 20 * i / 500));
	check_swing ("a sine of 20 Hz", s, 128, true, 19, 21, 7, 9);
	check_swing ("too few samples", s, 100, false);
	for (i = 0; i < 128; i++)
		s[i] = 0x80;
	check_swing ("no torque", s, 128, false);
	for (i = 0; i < 128; i++)
		s[i] = i < 60 ? 0x80 : 0x6B;
	check_swing ("a push", s, 128, false);
	for (i = 0; i < 128; i++)
		s[i] = (i / 30) % 2 ? 0x6B : 0x80;
	check_swing ("pushes every 60 ms", s, 128, false);
	for (i = 0; i < 128; i++)
		s[i] = (uint8_t) (0x70 + i / 8);
	check_swing ("a ramp", s, 128, false);
	for (i = 0; i < 128; i++)
		s[i] = (i / 9) % 2 ? 0x83 : 0x80;
	check_swing ("a force a frame, 3 steps", s, 128, false);
	for (i = 0; i < 128; i++)
		s[i] = (i / 35) % 2 ? 0x99 : 0x67;
	check_swing ("a shake of 5A 6A", s, 128, false);
}

/* Jambo! Safari's board simulated: the registers EPR-19338A writes */
static void
jambo (hl::DriveBoardJambo &b, TestServo &sv, uint8_t command, unsigned nmis, std::vector<uint8_t> *fe = NULL)
{
	for (unsigned i = 0; i < nmis; i++) {
		size_t before = sv.writes.size ();
		b.nmi (command, 0x80, sv);
		if (fe)
			for (size_t k = before; k < sv.writes.size (); k++)
				if (sv.writes[k].first == 0xFE)
					fe->push_back (sv.writes[k].second);
	}
}

static void
test_jambo ()
{
	hl::DriveBoardJambo b (NULL);
	TestServo sv;
	std::vector<uint8_t> fe;
	hl::DriveBoard::Swing swing = {};

	jambo (b, sv, 0xC1, 4);
	CHECK ("jambo C1: the motor free", sv.reg[0xFF], 0xFF);
	jambo (b, sv, 0xC7, 4);
	CHECK ("jambo C7: the gain", sv.reg[0xFB], 0xFF);
	CHECK ("jambo C7: the spring 0's FC", sv.reg[0xFC], 0x2C);
	CHECK ("jambo C7: its FD", sv.reg[0xFD], 0x24);
	CHECK ("jambo C7: no torque", sv.reg[0xFE], 0x80);
	jambo (b, sv, 0x25, 4);
	CHECK ("jambo 25: FB", sv.reg[0xFB], 0xAF);
	jambo (b, sv, 0x20, 4);
	CHECK ("jambo 20: FB", sv.reg[0xFB], 0x87);
	jambo (b, sv, 0x11, 4);
	CHECK ("jambo 11: FC", sv.reg[0xFC], 0x34);
	CHECK ("jambo 11: FD", sv.reg[0xFD], 0x25);
	jambo (b, sv, 0x17, 4);
	CHECK ("jambo 17: FC", sv.reg[0xFC], 0x64);
	CHECK ("jambo 17: FD", sv.reg[0xFD], 0x4A);
	jambo (b, sv, 0x54, 4);
	CHECK ("jambo 54: a push right", sv.reg[0xFE], 0x63);
	CHECK ("jambo 54: FD 00", sv.reg[0xFD], 0x00);
	jambo (b, sv, 0x64, 4);
	CHECK ("jambo 64: a push left", sv.reg[0xFE], 0x9D);
	jambo (b, sv, 0x01, 10);
	CHECK ("jambo 01 pushed: no road effect", sv.reg[0xFE], 0x9D);
	jambo (b, sv, 0x10, 4);
	CHECK ("jambo 10: the push ended, the road effect on again", sv.reg[0xFE] != 0x9D, 1);
	jambo (b, sv, 0x01, 200, &fe);
	CHECK ("jambo 01: a swing", hl::DriveBoard::find_swing (fe.data () + fe.size () - 128, 128, swing), 1);
	CHECK ("jambo 01: some 21 Hz", swing.period >= 20 && swing.period <= 28, 1);
	fe.clear ();
	jambo (b, sv, 0x02, 300, &fe);
	CHECK ("jambo 02: a bump at the end of the scale", std::count (fe.begin (), fe.end (), 0x00) >= 1, 1);
	jambo (b, sv, 0x00, 4);
	CHECK ("jambo 00: no road effect", sv.reg[0xFE], 0x80);
	jambo (b, sv, 0x9C, 4);
	CHECK ("jambo 9C: the motor idle", sv.reg[0xFF], 0xFF);
	sv.reg[0xFC] = 0;
	jambo (b, sv, 0x9C, 40);
	CHECK ("jambo 9C: then the spring", sv.reg[0xFC], 0x2C);
	jambo (b, sv, 0xCA, 4);
	jambo (b, sv, 0x81, 4);
	CHECK ("jambo test 81: a roll right", sv.reg[0xFE], 0x69);
	jambo (b, sv, 0x82, 4);
	CHECK ("jambo test 82: a roll left", sv.reg[0xFE], 0x97);
	jambo (b, sv, 0x80, 4);
	CHECK ("jambo test 80: stopped", sv.reg[0xFE], 0x80);
}

static hl::DriveBoardSr2 *board;
static TestServo *servo;

static void
run (uint8_t command, unsigned nmis, uint8_t wheel = 0x80)
{
	while (nmis--)
		board->nmi (command, wheel, *servo);
}

/* Through the start-up, to the main loop */
static void
start (void)
{
	board->reset ();
	run (0xFF, 4000 + 3 * 500);
}

/* SDL's main, through hl/core.h */
int
main (int argc, char **argv)
{
	(void) argc;
	(void) argv;
	board = new hl::DriveBoardSr2 ();
	servo = new TestServo ();

	/* The start-up's replies and lengths */
	board->reset ();
	run (0xFF, 1);
	CHECK ("set-up", board->reply (), 0xCF);
	CHECK ("set-up: the servo board idle", servo->reg[0xFF], 0xFF);
	run (0xFF, 3998);
	CHECK ("8 s of CF", board->reply (), 0xCF);
	run (0xFF, 1);
	CHECK ("then CE", board->reply (), 0xCE);
	/* The cockpit's centre in CE, the wheel's in CD */
	run (0x70, 500);
	CHECK ("then CD", board->reply (), 0xCD);
	run (0x78, 499);
	CHECK ("1 s of CD", board->reply (), 0xCD);
	run (0x78, 1);
	CHECK ("then CC, ready", board->reply (), 0xCC);
	run (0xB1, 500);
	CHECK ("then the status", board->reply (), 0x07);
	CHECK ("the motor free", servo->reg[0xFF], 0xFF);
	run (0xD3, 4);
	CHECK ("D3: the wheel's centre", board->reply (), 0x78);
	run (0xD4, 4);
	CHECK ("D4: the cockpit's centre", board->reply (), 0x70);

	/* A command counts at 4 NMIs */
	start ();
	run (0xF5, 3);
	CHECK ("3 NMIs: not yet", board->reply (), 0x07);
	run (0xF5, 1);
	CHECK ("4 NMIs: the echo", board->reply (), 0xF5);
	run (0xD1, 4);
	CHECK ("D1: DIP 1, the strength's row 4", board->reply (), 0xEF);
	run (0xD5, 4, 0x9A);
	CHECK ("D5: the wheel", board->reply (), 0x9A);
	run (0xD0, 4);
	CHECK ("D0: the status", board->reply (), 0x07);

	/* The torques, in a game only */
	start ();
	servo->writes.clear ();
	run (0x20, 4);
	CHECK ("a torque outside a game: nothing", servo->writes.size (), 0);
	run (0xC7, 4);
	CHECK ("C7: the strength's FD", servo->reg[0xFD], 0x31);
	CHECK ("C7: the strength's FC", servo->reg[0xFC], 0x2C);
	CHECK ("C7: the gain", servo->reg[0xFB], 0xFF);
	run (0x10, 4);
	CHECK ("10: left, FE 90", servo->reg[0xFE], 0x90);
	CHECK ("a torque's FD 11", servo->reg[0xFD], 0x11);
	run (0x3F, 4);
	CHECK ("3F: FE BF", servo->reg[0xFE], 0xBF);
	run (0x45, 4);
	CHECK ("45: right, FE 7B", servo->reg[0xFE], 0x7B);
	servo->writes.clear ();
	run (0x45, 40);
	CHECK ("the same torque again: nothing more", servo->writes.size (), 0);
	CHECK ("held", servo->reg[0xFE], 0x7B);
	/* Too short a command: not taken */
	run (0x30, 2);
	run (0x45, 10);
	CHECK ("a command of 2 NMIs: lost", servo->writes.size (), 0);

	/* Attract: the motor free; C2's shake, then FE 80 held */
	run (0xC1, 4);
	CHECK ("C1: the motor free", servo->reg[0xFF], 0xFF);
	servo->writes.clear ();
	run (0xC2, 4);
	run (0xC2, 300);
	CHECK ("C2: a torque an NMI", servo->writes.size (), 300);
	CHECK ("then FE 80", servo->reg[0xFE], 0x80);
	run (0x10, 4);
	CHECK ("a torque in attract: nothing", servo->reg[0xFE], 0x80);

	/* The test: CA, then 81 / 82 */
	run (0xCA, 4);
	run (0x81, 4);
	CHECK ("test 81: a push right", servo->reg[0xFE], 0x69);
	run (0x82, 4);
	CHECK ("test 82: a push left", servo->reg[0xFE], 0x97);

	/* CB: the start-up again from CE */
	run (0xCB, 4);
	CHECK ("CB: CE again", board->reply (), 0xCE);
	run (0xCB, 1000);
	CHECK ("then CC", board->reply (), 0xCC);

	delete board;
	delete servo;
	test_swings ();
	test_jambo ();
	printf ("driveboardtest: %d checks, %d failures\n", checks, failures);
	return failures ? 1 : 0;
}
